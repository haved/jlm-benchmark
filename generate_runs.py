#!/usr/bin/env python3

"""
This script creates separate .sh files for all configurations and iterations
"""

import shutil
import sys
from pathlib import Path
import os.path

DEST_FOLDER = Path("runs/")
# Applies to the regular configs. Some are only run once
DEFAULT_ITERATIONS_PER_CONFIG = 10

# By default disable everything
# The del keyword throws an error if we try to delete a missing key
DEFAULT_ENV = {
    "JLM_DISABLE_IMPLICIT_MODREF_REPRESENTATION": 1,

    "JLM_DISABLE_OMEGA_FOLDING": 1,

    "JLM_DISABLE_FUNCTION_SIMPLE_ALLOCA_ALLOWLIST": 1,
    "JLM_DISABLE_CALL_SIMPLE_ALLOCA_ALLOWLIST": 1,
    "JLM_DISABLE_EXTERN_SIMPLE_ALLOCA_ALLOWLIST": 1,

    "JLM_DISABLE_CONSTANT_MEMORY_BLOCKING": 1,
    "JLM_DISABLE_READ_ONLY_DETECTION": 1,

    "JLM_DISABLE_OPERATION_SIZE_BLOCKING": 1,
}

def createScript(name, flags, env, number):
    name_and_number = f"{name}-{number}"
    path = DEST_FOLDER / f"{name_and_number}.sh"

    # These folders are used for the final outputs
    statistics_out_dir = f"statistics-out/"
    statistics_out_file = os.path.join(statistics_out_dir, f"{name_and_number}.csv")
    echo_file = os.path.join(statistics_out_dir, f"{name_and_number}.echo")

    with open(path, 'w', encoding='utf-8') as fd:
        fd.write("#!/usr/bin/bash\n")
        fd.write(f"# ==== File generated by {sys.argv[0]}, do not edit! ====\n")
        fd.write("\n")
        fd.write("set -euo pipefail\n")
        fd.write('JLM_PATH="${JLM_PATH:-jlm}"\n')
        fd.write('PARALLEL_TASKS="${PARALLEL_TASKS:-1}"\n')
        fd.write('TMP_STATS_DIR="${TMP_STATS_DIR:-statistics}"\n')
        fd.write(f'echo "Run started at $(date) in SLURM job $SLURM_JOB_ID, array task $SLURM_ARRAY_TASK_ID" | tee -a "{echo_file}"\n')
        fd.write(f'echo "Benchmark checkout:" | tee -a "{echo_file}"\n')
        fd.write(f'git rev-parse HEAD | tee -a "{echo_file}"\n')
        fd.write(f'git status --porcelain | tee -a "{echo_file}"\n')
        fd.write(f'echo "Jlm checkout:" | tee -a "{echo_file}"\n')
        fd.write(f'git -C "${{JLM_PATH}}" rev-parse HEAD | tee -a "{echo_file}"\n')
        fd.write(f'git -C "${{JLM_PATH}}" status --porcelain | tee -a "{echo_file}"\n')
        fd.write("set -x\n")
        fd.write("\n")

        # If the statistics out file already exists, skip this job
        fd.write(f'if [ -f "{statistics_out_file}" ]; then\n')
        fd.write(f'echo "Configuration already done" >> "{echo_file}"\n')
        fd.write("exit 0\n")
        fd.write("fi\n")

        # Run the task, with all its environment variables
        fd.write("\n")
        for key, value in env.items():
            fd.write(f"export {key}={value}\n")

        # Avoid dumping full statistics for all runs, as it takes up too much disk (~300MB per run)
        if number > 0:
            fd.write("export JLM_DISABLE_MEMORY_STATE_DISTRIBUTION_STATISTICS=1\n")

        fd.write("\n")
        fd.write("./benchmark.py ")
        fd.write('"--jlm-opt=${JLM_PATH}/build-release/jlm-opt" ')
        fd.write('--llvmbin=/usr/lib/llvm-18/bin --sources=sources/sources.json -j="${PARALLEL_TASKS}" --statsdir="${TMP_STATS_DIR}" ')
        fd.write("--full-spec '--filter=5\\d\\d\\.' --filter=emacs --filter=gdb --filter=ghostscript --filter=sendmail ")
        fd.write("--noStrictAliasing ")
        fd.write(" ".join(flags) + " ")
        fd.write(f"--jlm-name {name_and_number} ")
        # Avoid outputting files, to save disk (~600MB per run)
        fd.write("--nullOutput\n")

        fd.write("\n")
        fd.write(f'echo "Done with status code $? at $(date)" >> "{echo_file}"\n')

        fd.write("\n")
        fd.write(f'echo "Aggregating statistics into single csv" >> "{echo_file}"\n')
        fd.write(f'python3 analysis/aggregate-memstates.py --stats-in="${{TMP_STATS_DIR}}/{name_and_number}" --stats-out="{statistics_out_file}"\n')
        fd.write("\n")
        fd.write('if [ ! -z "${CLEAN_TMP_STATS_DIR+x}" ]; then\n')
        fd.write(f'rm -rf "${{TMP_STATS_DIR}}/{name_and_number}"\n')
        fd.write("fi\n")


def createScripts(iterations, optPipeline, modRefType, enableRcaf, enableOmegaFolding, enableCmf, enableOsf):
    name = []
    env = DEFAULT_ENV.copy()
    flags = []

    if optPipeline == "O0":
        flags.extend(["--pre-jlm-name", "clangO0"])
    elif optPipeline == "Oz":
        flags.extend(["--clangOz", "--pre-jlm-name", "clangOz"])
    elif optPipeline == "sroa":
        flags.extend(["--optSroa", "--pre-jlm-name", "sroa"])
    else:
        raise ValueError("Other opt pipelines not defined")
    name.append(optPipeline)

    if modRefType == "raw":
        flags.append("--regionAwareModRef")
    elif modRefType == "raw-ip":
        flags.append("--regionAwareModRef")
        del env["JLM_DISABLE_IMPLICIT_MODREF_REPRESENTATION"]
    elif modRefType == "rag":
        flags.append("--agnosticModRef")
    elif modRefType == "noPtG":
        pass # Do nothing
    elif modRefType == "PtGAA":
        env["JLM_ENABLE_SVF_PTGAA"] = 1
    else:
        raise ValueError(f"Unknown modRefType: {modRefType}")
    name.append(modRefType)

    if enableRcaf:
        del env["JLM_DISABLE_FUNCTION_SIMPLE_ALLOCA_ALLOWLIST"]
        del env["JLM_DISABLE_CALL_SIMPLE_ALLOCA_ALLOWLIST"]
        del env["JLM_DISABLE_EXTERN_SIMPLE_ALLOCA_ALLOWLIST"]
        name.append("rcaf")
        # Register confined allocas only exist in the region aware summarizer
        assert "raw" in modRefType

    if enableOmegaFolding:
        del env["JLM_DISABLE_OMEGA_FOLDING"]
        name.append("omf")
        assert "raw" in modRefType or "rag" in modRefType

    if enableCmf:
        del env["JLM_DISABLE_CONSTANT_MEMORY_BLOCKING"]
        del env["JLM_DISABLE_READ_ONLY_DETECTION"]
        name.append("cmf")
        assert "raw" in modRefType or "rag" in modRefType

    if enableOsf:
        del env["JLM_DISABLE_OPERATION_SIZE_BLOCKING"]
        name.append("osf")
        assert "raw" in modRefType or "rag" in modRefType

    name_string = "-".join(name)
    for i in range(iterations):
        createScript(name_string, flags, env, i)

def pickOsf(**kwargs):
    createScripts(enableOsf=True, **kwargs)
    createScripts(enableOsf=False, **kwargs)

def pickCmf(**kwargs):
    pickOsf(enableCmf=True, **kwargs)
    pickOsf(enableCmf=False, **kwargs)

def pickOmegaFolding(**kwargs):
    pickCmf(enableOmegaFolding=True, **kwargs)
    pickCmf(enableOmegaFolding=False, **kwargs)

def pickRcaf(**kwargs):
    pickOmegaFolding(enableRcaf=True, **kwargs)
    pickOmegaFolding(enableRcaf=False, **kwargs)

def pickModRefType(**kwargs):
    # Rcaf is always false for rag
    pickOmegaFolding(modRefType="rag", enableRcaf=False, **kwargs)

    pickRcaf(modRefType="raw", **kwargs)
    pickRcaf(modRefType="raw-ip", **kwargs)

def pickOptPipeline(**kwargs):
    pickModRefType(optPipeline="sroa", **kwargs)

def main():
    if DEST_FOLDER.exists():
        shutil.rmtree(DEST_FOLDER)
    DEST_FOLDER.mkdir()

    # Every pipeline combination on top of sroa
    pickOptPipeline(iterations=DEFAULT_ITERATIONS_PER_CONFIG)

    # Using no PtG
    createScripts(iterations=1,
                  optPipeline="sroa",
                  modRefType="noPtG",
                  enableRcaf=False,
                  enableOmegaFolding=False,
                  enableCmf=False,
                  enableOsf=False)

    # Using PtG only as AA in SVF
    createScripts(iterations=1,
                  optPipeline="sroa",
                  modRefType="PtGAA",
                  enableRcaf=False,
                  enableOmegaFolding=False,
                  enableCmf=False,
                  enableOsf=False)

    #### Performing selected pipelines on top of clang O0 and Oz ####
    for clang in ["O0", "Oz"]:
        # Using no PtG
        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="noPtG",
                      enableRcaf=False,
                      enableOmegaFolding=False,
                      enableCmf=False,
                      enableOsf=False)

        # Using PtG only as AA in SVF
        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="PtGAA",
                      enableRcaf=False,
                      enableOmegaFolding=False,
                      enableCmf=False,
                      enableOsf=False)

        # Using region agnostic with everything enabled
        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="rag",
                      enableRcaf=False,
                      enableOmegaFolding=True,
                      enableCmf=True,
                      enableOsf=True)

        # Using our best pipeline
        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="raw-ip",
                      enableRcaf=True,
                      enableOmegaFolding=True,
                      enableCmf=True,
                      enableOsf=True)

        # "Ablation study" of raw-ip on top of clang Oz
        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="raw-ip",
                      enableRcaf=False,
                      enableOmegaFolding=True,
                      enableCmf=True,
                      enableOsf=True)

        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="raw-ip",
                      enableRcaf=True,
                      enableOmegaFolding=False,
                      enableCmf=True,
                      enableOsf=True)

        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="raw-ip",
                      enableRcaf=True,
                      enableOmegaFolding=True,
                      enableCmf=False,
                      enableOsf=True)

        createScripts(iterations=1,
                      optPipeline=clang,
                      modRefType="raw-ip",
                      enableRcaf=True,
                      enableOmegaFolding=True,
                      enableCmf=True,
                      enableOsf=False)

if __name__ == "__main__":
    main()
